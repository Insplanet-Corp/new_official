-- ============================================================================
-- '메인관리' 메뉴 제거에 따른 권한 정리
--
-- 어드민의 메인관리 탭을 없앴다(포트폴리오관리에서 [메인] 체크로 처리한다).
-- admin_users.permissions 에 남은 '/admin/main' 은 이제 어느 탭과도 짝이
-- 없어 화면에 아무 영향을 주지 않지만, 사용자관리 수정 화면에서 체크박스로
-- 되살릴 수도 없는 유령 값이라 지운다.
--
-- 실행: Supabase 대시보드 > SQL Editor. 선행 001.
-- ============================================================================

update public.admin_users
   set permissions = array_remove(permissions, '/admin/main')
 where '/admin/main' = any (permissions);

-- ⚠️ 이 UPDATE 는 admin_users 쓰기 RLS 를 타므로 SQL Editor(서비스 롤)에서
--    실행해야 한다. 어드민 화면에서는 돌지 않는다.
--
-- ⚠️ 002_admin_users_sync.sql 의 기본 권한 배열에는 '/admin/main' 이 그대로
--    남아 있다(이미 실행된 마이그레이션이라 손대지 않았다). 새 환경을 001→002
--    순서로 세팅했다면 002 다음에 이 013 을 한 번 더 돌려 유령 값을 지울 것.

