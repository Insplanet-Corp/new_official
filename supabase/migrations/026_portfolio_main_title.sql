-- ============================================================================
-- 메인 슬라이드 전용 제목 (main_title)
--
-- 홈 "Our Projects" 슬라이드는 지금까지 `title`(포트폴리오 프로젝트명)을 그대로
-- 썼다. 그런데 목록에 쓰기 좋은 이름과 메인 슬라이드에 크게 걸기 좋은 이름이
-- 늘 같지는 않다 — 슬라이드는 두 줄로 크게 들어가고 문구도 더 짧은 편이 낫다.
-- 그래서 메인 전용 제목을 따로 받는다(사용자 결정, 2026-09-02).
--
-- 비어 있으면 화면이 `title` 로 되돌아간다(data/home.ts 의 toShowcase). 그래서
-- 기존 행을 백필할 필요가 없고, 이 마이그레이션을 안 돌려도 화면이 안 깨진다
-- (조회 코드가 `select('*')` 라 컬럼이 없으면 그냥 undefined 다).
--
-- 줄바꿈 규칙은 `title` 과 **똑같다** — 어드민 입력칸에는 역슬래시+n 두 글자를
-- 치고 DB 에는 진짜 개행으로 저장한다. 변환은 lib/portfolios.ts 의 toRow/toDraft
-- 가 경계에서 한다. 규칙을 하나로 두려고 일부러 '|' 같은 새 구분자를 안 만들었다.
--
-- 실행: Supabase 대시보드 > SQL Editor. 선행 010·011.
-- ============================================================================

alter table public.portfolios
  add column if not exists main_title text;

comment on column public.portfolios.main_title is
  '홈 메인 슬라이드에 걸 제목. 비어 있으면 title 을 쓴다.
   \n 으로 줄바꿈을 지정한다(title 과 같은 규칙 — DB 에는 진짜 개행으로 저장).';

